//! Character classification and case mapping. Phase 2: ASCII, Latin-1,
//! Latin Extended-A, Greek and Cyrillic; generated Unicode tables replace
//! this in Phase 4.

pub fn isDigit(cp: u21) bool {
    return digitValue(cp) != null;
}

/// Decimal digit ranges (Unicode Nd, the common blocks)
const digit_zeros = [_]u21{ '0', 0x660, 0x6F0, 0x7C0, 0x966, 0x9E6, 0xA66, 0xAE6, 0xB66, 0xBE6, 0xC66, 0xCE6, 0xD66, 0xE50, 0xED0, 0xF20, 0x1040, 0xFF10 };

pub fn digitValue(cp: u21) ?u8 {
    for (digit_zeros) |z| if (cp >= z and cp <= z + 9) return @intCast(cp - z);
    return null;
}

pub fn isWhitespace(cp: u21) bool {
    return switch (cp) {
        ' ', '\t', '\n', 0x0B, 0x0C, '\r', 0x1C...0x1F, 0x85, 0x1680, 0x2000...0x2006, 0x2008...0x200A, 0x2028, 0x2029, 0x205F, 0x3000 => true,
        else => false,
    };
}

pub fn isUpper(cp: u21) bool {
    return downcase(cp) != cp or cp == 0x3D2;
}

pub fn isLower(cp: u21) bool {
    return upcase(cp) != cp or cp == 0xDF or cp == 0xAA or cp == 0xBA;
}

pub fn isAlphabetic(cp: u21) bool {
    return switch (cp) {
        'a'...'z', 'A'...'Z', 0xAA, 0xB5, 0xBA, 0xC0...0xD6, 0xD8...0xF6, 0xF8...0x2C1, 0x370...0x373, 0x376, 0x377, 0x37B...0x37D, 0x386, 0x388...0x3FF, 0x400...0x481, 0x48A...0x52F, 0x531...0x556, 0x561...0x587, 0x5D0...0x5EA, 0x620...0x64A, 0x904...0x939, 0x1E00...0x1FFF, 0x3041...0x3096, 0x30A1...0x30FA, 0x4E00...0x9FFF, 0xAC00...0xD7A3 => true,
        else => false,
    };
}

pub fn upcase(cp: u21) u21 {
    return switch (cp) {
        'a'...'z' => cp - 32,
        0xB5 => 0x39C,
        0xE0...0xF6, 0xF8...0xFE => cp - 32,
        0xFF => 0x178,
        0x100...0x137, 0x14A...0x177 => if (cp & 1 == 1) cp - 1 else cp,
        0x139...0x148, 0x179...0x17E => if (cp & 1 == 0) cp - 1 else cp,
        0x3B1...0x3C1, 0x3C3...0x3CB => cp - 32,
        0x3C2 => 0x3A3,
        0x3AC => 0x386,
        0x3AD...0x3AF => cp - 37,
        0x3CC => 0x38C,
        0x3CD, 0x3CE => cp - 63,
        0x430...0x44F => cp - 32,
        0x450...0x45F => cp - 80,
        0x460...0x481, 0x48A...0x4BF, 0x4D0...0x52F => if (cp & 1 == 1) cp - 1 else cp,
        else => cp,
    };
}

pub fn downcase(cp: u21) u21 {
    return switch (cp) {
        'A'...'Z' => cp + 32,
        0xC0...0xD6, 0xD8...0xDE => cp + 32,
        0x178 => 0xFF,
        0x100...0x137, 0x14A...0x177 => if (cp & 1 == 0) cp + 1 else cp,
        0x139...0x148, 0x179...0x17E => if (cp & 1 == 1) cp + 1 else cp,
        0x391...0x3A1, 0x3A3...0x3AB => cp + 32,
        0x386 => 0x3AC,
        0x388...0x38A => cp + 37,
        0x38C => 0x3CC,
        0x38E, 0x38F => cp + 63,
        0x410...0x42F => cp + 32,
        0x400...0x40F => cp + 80,
        0x460...0x481, 0x48A...0x4BF, 0x4D0...0x52F => if (cp & 1 == 0) cp + 1 else cp,
        else => cp,
    };
}

pub fn foldcase(cp: u21) u21 {
    return switch (cp) {
        0x3C2 => 0x3C3, // final sigma folds to sigma
        else => downcase(cp),
    };
}
